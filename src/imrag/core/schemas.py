from typing import Optional

from pydantic import BaseModel, Field

class SourceChunk(BaseModel):
    """Represents a chunk of text from a source document."""
    index: int = Field(..., description="Index of the chunk in the source document.")
    source_id: str = Field(..., description="Unique identifier for the source document.")
    chunk_id: str = Field(..., description="Unique identifier for the chunk within the source document.")
    text: str = Field(..., description="The actual text content of the chunk.")
    source: Optional[str] = Field(None, description="Display name of the source document.")
    page: Optional[int] = Field(None, description="1-based page number, when available.")
    metadata: Optional[dict] = Field(default_factory=dict, description="Optional metadata associated with the chunk.")

class Embedding(BaseModel):
    """Represents an embedding vector for a chunk of text."""
    chunk_id: str = Field(..., description="Unique identifier for the chunk that this embedding represents.")
    vector: list[float] = Field(..., description="The embedding vector.")

class RetrievalResult(BaseModel):
    """Represents a result from a retrieval operation."""
    chunk: SourceChunk = Field(..., description="The chunk that was retrieved.")
    score: float = Field(..., description="The relevance score of the retrieved chunk.")

class RerankingResult(BaseModel):
    """Represents a result from a reranking operation."""
    chunk: SourceChunk = Field(..., description="The chunk that was reranked.")
    score: float = Field(..., description="The new relevance score after reranking.")

class Timings(BaseModel):
    """Represents timing information for various stages of processing."""
    retrieve_ms: Optional[float] = Field(None, description="Time spent retrieving sources in milliseconds.")
    rerank_ms: Optional[float] = Field(None, description="Time spent reranking sources in milliseconds.")
    generate_ms: Optional[float] = Field(None, description="Time spent generating the answer in milliseconds.")
    total_ms: Optional[float] = Field(None, description="Total request time in milliseconds.")

class RAGResponse(BaseModel):
    """Represents an answer generated by the LLM."""
    question: str = Field(..., description="The original question asked by the user.")
    answer: str = Field(..., description="The answer generated by the LLM.")
    sources: list[SourceChunk] = Field(..., description="List of source chunks that support the answer.")
    timings: Timings = Field(..., description="Timing information for various stages of processing.")





